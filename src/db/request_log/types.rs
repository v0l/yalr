#[derive(Default)]
pub struct Filter<'a> {
    pub before: Option<i64>,
    pub model: Option<&'a str>,
    pub status: Option<&'a str>,
    pub user_id: Option<i64>,
    pub api_key_id: Option<i64>,
    pub since_ms: Option<i64>,
    pub endpoint: Option<&'a str>,
}


